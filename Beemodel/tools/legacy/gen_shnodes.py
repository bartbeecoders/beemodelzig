#!/usr/bin/env python3
"""src/shnodes.zig from the assembly BeeModel's matnodes.s: the shader node
catalogue (each type's script name, title, inputs, values, choices, outputs,
their kinds, header colour, category). Reads the source, runs nothing.

    python3 tools/gen_shnodes.py [../BeeModel/src/matnodes.s] > src/shnodes.zig
"""
import os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = open(sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, '..', 'BeeModel', 'src', 'matnodes.s')).read()

strs = dict(re.findall(r'^(mns_\d+):\s+\.asciz "(.*)"', src, re.M))


def label(name):
    m = re.search(r'^' + re.escape(name) + r':\s+\.(quad|byte|long)\s+(.*)$', src, re.M)
    if not m:
        raise SystemExit('no ' + name)
    return [x.strip() for x in m.group(2).split('#')[0].split(',')]


def s(x):
    return None if x == '0' else strs[x]


names = [strs[x.strip()] for x in re.search(r'graph_type_names:\s*((?:\s*\.quad [^\n]*\n)+)', src).group(1).replace('.quad', ',').replace('\n', '').split(',') if x.strip() and x.strip() != '0']
titles_blk = re.search(r'mn_titles:\s*((?:\s*\.quad [^\n]*\n)+)', src).group(1)
titles = [x.strip() for x in titles_blk.replace('.quad', ',').replace('\n', '').split(',') if x.strip()][1:]
titles = [strs[x] for x in titles]
assert len(names) == 42 and len(titles) == 42, (len(names), len(titles))

meta_blk = re.search(r'mn_meta:\s*((?:\s*\.quad [^\n]*\n)+)', src).group(1)
rows = [[x.strip() for x in l.replace('.quad', '').split(',')] for l in meta_blk.strip().split('\n')]
rows = rows[1:]  # (type 0)
assert len(rows) == 42

colors = re.findall(r'^\s+\.long (0x[0-9a-f]+)\s+# (\w+)', src[src.index('mn_color:'):src.index('mn_cat:')], re.M)
assert len(colors) == 42
cats = [int(x) for x in label('mn_cat')[1]] if False else [int(x) for x in re.search(r'mn_cat:\s+\.byte ([^\n]*)', src).group(1).split(',')]
cat_names = [strs[x.strip()] for x in re.search(r'mn_cat_names:\s+\.quad ([^\n]*)', src).group(1).split(',') if x.strip() != '0']

out = []
w = out.append
w('// Generated by tools/gen_shnodes.py from the assembly BeeModel sources (matnodes.s).')
w('// Do not edit. The shader node catalogue: per type (1..42) its script name, title,')
w('// inputs (3), values (4), the values\' choices, outputs (8), their kinds, header')
w('// colour and category, as the node editor, the Material tab, scripts and agents read')
w('// them. Kinds: inputs and outputs 0 none, 1 value, 2 vector, 3 colour; values 0 a')
w('// number, 1 a choice, 6 the second choice list, 2 an image, 3 a whole number, 4 a function.')
w('')
w('pub const Meta = struct {')
w('    name: []const u8,')
w('    title: []const u8,')
w('    inputs: [3]?[]const u8,')
w('    in_kinds: [3]u8,')
w('    values: [4]?[]const u8,')
w('    val_kinds: [4]u8,')
w('    /// the choices of kind-1 values, then of kind-6 ones')
w('    choices: []const []const u8 = &.{},')
w('    choices2: []const []const u8 = &.{},')
w('    outputs: [8]?[]const u8,')
w('    out_kinds: [8]u8,')
w('    color: u32,')
w('    cat: u8,')
w('};')
w('')
w('pub const cat_names = [_][]const u8{ ' + ', '.join('"%s"' % c for c in cat_names) + ' };')
w('')


def zl(lst):
    return '.{ ' + ', '.join('null' if v is None else '"%s"' % v for v in lst) + ' }'


def zb(lst):
    return '.{ ' + ', '.join(lst) + ' }'


w('/// By type - 1.')
w('pub const metas = [42]Meta{')
for t in range(42):
    mi, mik, mv, mvk, mc, mo, mok = rows[t]
    ins = [s(x) for x in label(mi)]
    vals = [s(x) for x in label(mv)]
    outs = [s(x) for x in label(mo)]
    ik, vk, ok = label(mik), label(mvk), label(mok)
    ch = ch2 = []
    if mc != '0':
        c = label(mc)
        n = int(c[0])
        ch = [strs[x] for x in c[1:1 + n]]
        if len(c) > 1 + n:
            n2 = int(c[1 + n])
            ch2 = [strs[x] for x in c[2 + n:2 + n + n2]]
    col, cname = colors[t]
    assert cname == names[t], (cname, names[t])
    w('    .{')
    w(f'        .name = "{names[t]}",')
    w(f'        .title = "{titles[t]}",')
    w(f'        .inputs = {zl(ins)},')
    w(f'        .in_kinds = {zb(ik)},')
    w(f'        .values = {zl(vals)},')
    w(f'        .val_kinds = {zb(vk)},')
    if ch:
        w('        .choices = &.{ ' + ', '.join('"%s"' % x for x in ch) + ' },')
    if ch2:
        w('        .choices2 = &.{ ' + ', '.join('"%s"' % x for x in ch2) + ' },')
    w(f'        .outputs = {zl(outs)},')
    w(f'        .out_kinds = {zb(ok)},')
    w(f'        .color = {col},')
    w(f'        .cat = {cats[t + 1]},')
    w('    },')
w('};')
w('')
w('/// The type (1..) of a script name, or null.')
w('pub fn typeOf(name: []const u8) ?u32 {')
w('    for (&metas, 1..) |*m, i| {')
w('        if (std.mem.eql(u8, m.name, name)) return @intCast(i);')
w('    }')
w('    return null;')
w('}')
w('')
w('/// A type\'s row, or null (0, or past the last).')
w('pub fn of(t: u32) ?*const Meta {')
w('    return if (t >= 1 and t <= metas.len) &metas[t - 1] else null;')
w('}')
w('')
w('const std = @import("std");')
w('')
w('test "the catalogue: 42 types, names as graph.s parses them, every row filled" {')
w('    const gops = @import("graphops.zig");')
w('    try std.testing.expectEqual(@as(usize, 42), metas.len);')
w('    for (&metas, 1..) |*m, i| {')
w('        try std.testing.expectEqual(@as(?u32, @intCast(i)), gops.typeIndex(m.name));')
w('        try std.testing.expectEqualStrings(gops.type_titles[i - 1], m.title);')
w('        try std.testing.expect(m.color != 0 and m.cat < cat_names.len);')
w('        for (m.val_kinds, m.values) |k, v| {')
w('            if (k == 1) try std.testing.expect(v != null and m.choices.len > 0);')
w('            if (k == 6) try std.testing.expect(v != null and m.choices2.len > 0);')
w('        }')
w('    }')
w('    try std.testing.expectEqualStrings("Arctan2", metas[6].choices[27]);')
w('    try std.testing.expectEqual(@as(?u32, 42), typeOf("fncall"));')
w('}')
print('\n'.join(out))
