#!/usr/bin/env python3
"""Generate src/aisafe.zig from the assembly BeeModel sources: the ids of the
operators the original flags OPF_AI_SAFE (agents may run them as MCP tools
op_<id>), in the original's link order (src/*.s sorted, then the order in
each file), which is also src/catalog.zig's order.

    tools/gen_aisafe.py [path/to/BeeModel]   (default: ../BeeModel)
"""
import glob
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SRC = os.path.join(sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "..", "BeeModel"), "src")
POSITIONAL = ["sym", "name", "label", "exec", "check", "arg", "key", "flags", "doc", "params", "poll", "form"]


def split_args(s):
    out, cur, q, i = [], "", False, 0
    while i < len(s):
        ch = s[i]
        if q and ch == "\\" and i + 1 < len(s):
            cur += s[i:i + 2]
            i += 2
            continue
        if ch == '"':
            q = not q
        if ch == "," and not q:
            out.append(cur.strip())
            cur = ""
        else:
            cur += ch
        i += 1
    if cur.strip():
        out.append(cur.strip())
    return out


# OPERATOR's flags default to OPF_AI_SAFE (macros.inc); given flags are an
# expression of the OPF_* constants
CONST = {m.group(1): int(m.group(2), 0) for m in re.finditer(
    r"^\.equ\s+(OPF_[A-Z_]+),\s*(\w+)", open(os.path.join(SRC, "macros.inc")).read(), re.M)}


def flags_of(expr):
    if expr is None:
        return CONST["OPF_AI_SAFE"]
    v = 0
    for tok in expr.split("|"):
        tok = tok.strip()
        v |= CONST[tok] if tok in CONST else int(tok, 0)
    return v


safe, quiet, seen = [], [], set()
for path in sorted(glob.glob(os.path.join(SRC, "*.s"))):
    for line in open(path, encoding="utf-8", errors="replace"):
        m = re.match(r"^\s*OPERATOR\s+(.*)$", line)
        if not m:
            continue
        f, pos = {}, 0
        for a in split_args(m.group(1)):
            km = re.match(r"^([a-z]+)=(.*)$", a, re.S)
            if km and km.group(1) in POSITIONAL:
                f[km.group(1)] = km.group(2).strip()
            else:
                if pos < len(POSITIONAL):
                    f[POSITIONAL[pos]] = a
                pos += 1
        if f["sym"] in seen:
            continue
        seen.add(f["sym"])
        fl = flags_of(f.get("flags"))
        if fl & CONST["OPF_AI_SAFE"]:
            safe.append(f["name"].strip().strip('"'))
        if fl & CONST["OPF_QUIET"]:
            quiet.append(f["name"].strip().strip('"'))

out = ["// Generated by tools/gen_aisafe.py from the assembly BeeModel sources. Do not edit.\n",
       "// The operators the original flags OPF_AI_SAFE: AI agents may run them (MCP\n",
       "// tools op_<id with dots as underscores>, run_operator, BeeScript's op() in an\n",
       "// agent's script). In the original's order (src/catalog.zig's too).\n\n",
       "pub const ids = [_][]const u8{\n"]
for s in safe:
    out.append('    "%s",\n' % s)
out.append("};\n\n")
out.append("/// The operators flagged OPF_QUIET: run_op does not echo \"> Label\" for them.\n")
out.append("pub const quiet = [_][]const u8{\n")
for s in quiet:
    out.append('    "%s",\n' % s)
out.append("};\n")
dst = os.path.join(ROOT, "src", "aisafe.zig")
open(dst, "w", encoding="utf-8").write("".join(out))
print("%d agent-safe, %d quiet operators -> %s" % (len(safe), len(quiet), dst))
